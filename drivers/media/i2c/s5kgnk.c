static int s5kgnk_power_on(struct device *dev)
{
	struct s5kgnk *gnk = to_s5kgnk(dev_get_drvdata(dev));
	int i, ret;

	for (i = 0; i < ARRAY_SIZE(s5kgnk_supplies); i++) {
		ret = regulator_enable(gnk->supplies[i]);
		if (ret) {
			dev_err(dev, "%s: %d\n", s5kgnk_supplies[i], ret);
			while (i-- > 0)
				regulator_disable(gnk->supplies[i]);
			return ret;
		}
		if (s5kgnk_supply_delay_us[i])
			fsleep(s5kgnk_supply_delay_us[i]);
	}
	gpiod_set_value_cansleep(gnk->reset, 1);
	fsleep(1000);
	ret = clk_prepare_enable(gnk->mclk);
	if (ret)
		dev_err(dev, "mclk: %d\n", ret);
	fsleep(9000);
	return ret;
}

static int s5kgnk_power_off(struct device *dev)
{
	struct s5kgnk *gnk = to_s5kgnk(dev_get_drvdata(dev));
	int i;

	clk_disable_unprepare(gnk->mclk);
	gpiod_set_value_cansleep(gnk->reset, 0);
	for (i = ARRAY_SIZE(s5kgnk_supplies); i-- > 0;)
		regulator_disable(gnk->supplies[i]);
	return 0;
}

static int s5kgnk_probe(struct i2c_client *client)
{
	struct device *dev = &client->dev;
	struct s5kgnk *gnk;
	u64 id;
	int i, ret;

	gnk = devm_kzalloc(dev, sizeof(*gnk), GFP_KERNEL);
	if (!gnk)
		return -ENOMEM;
	v4l2_i2c_subdev_init(&gnk->sd, client, &s5kgnk_subdev_ops);
	gnk->regmap = devm_cci_regmap_init_i2c(client, 16);
	if (IS_ERR(gnk->regmap))
		return PTR_ERR(gnk->regmap);
	for (i = 0; i < ARRAY_SIZE(s5kgnk_supplies); i++) {
		gnk->supplies[i] = devm_regulator_get(dev, s5kgnk_supplies[i]);
		if (IS_ERR(gnk->supplies[i]))
			return dev_err_probe(dev, PTR_ERR(gnk->supplies[i]), "%s\n", s5kgnk_supplies[i]);
	}
	gnk->reset = devm_gpiod_get(dev, "reset", GPIOD_OUT_LOW);	/* high = run */
	if (IS_ERR(gnk->reset))
		return dev_err_probe(dev, PTR_ERR(gnk->reset), "reset gpio\n");
	gnk->mclk = devm_clk_get(dev, "mclk");
	if (IS_ERR(gnk->mclk))
		return dev_err_probe(dev, PTR_ERR(gnk->mclk), "mclk\n");

	ret = s5kgnk_power_on(dev);
	if (ret)
		return ret;
	ret = cci_read(gnk->regmap, S5KGNK_REG_ID, &id, NULL);
	if (!ret && id != S5KGNK_ID)
		ret = -ENODEV;
	if (ret) {
		dev_err(dev, "chip id 0x%llx: %d\n", id, ret);
		s5kgnk_power_off(dev);
		return ret;
	}

	ret = s5kgnk_init_controls(gnk);
	if (ret)
		goto err_power;
	gnk->sd.internal_ops = &s5kgnk_internal_ops;
	gnk->sd.flags = V4L2_SUBDEV_FL_HAS_DEVNODE;
	gnk->sd.entity.function = MEDIA_ENT_F_CAM_SENSOR;
	gnk->pad.flags = MEDIA_PAD_FL_SOURCE;
	ret = media_entity_pads_init(&gnk->sd.entity, 1, &gnk->pad);
	if (ret)
		goto err_ctrls;
	ret = v4l2_subdev_init_finalize(&gnk->sd);
	if (ret)
		goto err_entity;

	pm_runtime_get_noresume(dev);
	pm_runtime_set_active(dev);
	pm_runtime_enable(dev);
	pm_runtime_set_autosuspend_delay(dev, 1000);
	pm_runtime_use_autosuspend(dev);
	pm_runtime_put_autosuspend(dev);

	ret = v4l2_async_register_subdev_sensor(&gnk->sd);
	if (ret)
		goto err_pm;
	return 0;

err_pm:
	pm_runtime_disable(dev);
	pm_runtime_get_noresume(dev);
	v4l2_subdev_cleanup(&gnk->sd);
err_entity:
	media_entity_cleanup(&gnk->sd.entity);
err_ctrls:
	v4l2_ctrl_handler_free(&gnk->ctrls);
err_power:
	s5kgnk_power_off(dev);
	return ret;
}

static void s5kgnk_remove(struct i2c_client *client)
{
	struct v4l2_subdev *sd = i2c_get_clientdata(client);
	struct s5kgnk *gnk = to_s5kgnk(sd);

	v4l2_async_unregister_subdev(sd);
	v4l2_subdev_cleanup(sd);
	media_entity_cleanup(&sd->entity);
	v4l2_ctrl_handler_free(&gnk->ctrls);
	pm_runtime_disable(&client->dev);
	if (!pm_runtime_status_suspended(&client->dev))
		s5kgnk_power_off(&client->dev);
	pm_runtime_set_suspended(&client->dev);
}

static const struct dev_pm_ops s5kgnk_pm_ops = {
	RUNTIME_PM_OPS(s5kgnk_power_off, s5kgnk_power_on, NULL)
};

static const struct of_device_id s5kgnk_of_match[] = {
	{ .compatible = "samsung,s5kgnk" },
	{ }
};
MODULE_DEVICE_TABLE(of, s5kgnk_of_match);

static struct i2c_driver s5kgnk_driver = {
	.driver = {
		.name = "s5kgnk",
		.of_match_table = s5kgnk_of_match,
		.pm = pm_ptr(&s5kgnk_pm_ops),
	},
	.probe = s5kgnk_probe,
	.remove = s5kgnk_remove,
};
module_i2c_driver(s5kgnk_driver);

