/* 16-bit registers on page 0x4000 (0xfcfc selects the page) */
#define S5KGNK_REG_PAGE		CCI_REG16(0xfcfc)
#define S5KGNK_PAGE_CTRL	0x4000
#define S5KGNK_REG_ID		CCI_REG16(0x0000)
#define S5KGNK_ID		0x08ef
