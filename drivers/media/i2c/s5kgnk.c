#define S5KGNK_WIDTH		4032
#define S5KGNK_HEIGHT		3024
#define S5KGNK_LLP		0x18b0
#define S5KGNK_FLL		0x2958
#define S5KGNK_FLL_MAX		0xffff
#define S5KGNK_EXPOSURE_MARGIN	16
#define S5KGNK_AGAIN_MIN	0x20	/* gain = code / 32 */
#define S5KGNK_AGAIN_MAX	0x400
/* vt PLL: 24 MHz EXTCLK / 3 * 245; the mode's FLL x LLP at it is ~29 fps */
