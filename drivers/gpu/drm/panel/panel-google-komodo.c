/*
 * Copyright (c) Google LLC
 *
 * "Boot handoff" panel driver for the Pixel 9 Pro XL (komodo) MIPI-DSI
 * display.
 *
 * The bootloader fully initialises this panel - DCPHY PLL, DSIM link and the
 * panel's own power-on command sequence - and leaves it streaming (that is
 * what the simple-framebuffer splash is drawn into). This driver therefore
 * does NOT re-initialise the panel: prepare()/enable() are no-ops so the
 * running link is preserved, and the exynos9 DECON simply takes over scanning
 * its own framebuffer into the already-configured DSIM -> panel path.
 *
 * All this driver contributes is the DRM plumbing the DSI host needs: the DSI
 * device parameters (lane count, pixel format, command/video mode) and the
 * fixed native mode. Only the active resolution matters to the DECON; the
 * blanking is generated by the DSIM, which keeps the bootloader's values.
 */

