struct komodo_panel {
	struct drm_panel panel;
	struct mipi_dsi_device *dsi;
	/*
	 * Cached in get_modes() so enable() can read the active mode's refresh
	 * rate (connector->state->crtc->state), the idiomatic way a drm_panel
	 * learns its mode - see panel-novatek-nt35950.c. drm_panel itself has no
	 * mode_set callback.
	 */
	struct drm_connector *connector;
	struct gpio_desc *reset_gpio;
};

